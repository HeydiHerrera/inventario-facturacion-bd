-- ---------- 2.1 Secuencias para numeros correlativos ----------
CREATE SEQUENCE SEQ_NUM_FACTURA START WITH 15 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_NUM_ORDEN   START WITH 15 INCREMENT BY 1 NOCACHE;

-- ---------- 2.2 Tablas maestras y catalogos ----------
CREATE TABLE CATEGORIAS (
    ID_Categoria     NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Nombre_Categoria VARCHAR2(50)  NOT NULL UNIQUE,
    Descripcion      VARCHAR2(150) NULL
);

CREATE TABLE PROVEEDORES (
    ID_Proveedor       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Nombre_Empresa     VARCHAR2(100) NOT NULL,
    NIT                VARCHAR2(15)  NOT NULL UNIQUE,
    Telefono           VARCHAR2(15)  NOT NULL,
    Correo             VARCHAR2(100) NOT NULL UNIQUE,
    Contacto_Principal VARCHAR2(100) NULL,
    CONSTRAINT CK_Prov_Correo CHECK (REGEXP_LIKE(Correo, '^[^@ ]+@[^@ ]+\.[^@ ]+$'))
);

CREATE TABLE CLIENTES (
    ID_Cliente      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NIT             VARCHAR2(15)  NOT NULL UNIQUE,
    Nombre_Completo VARCHAR2(100) NOT NULL,
    Direccion       VARCHAR2(200) NULL,
    Telefono        VARCHAR2(15)  NULL,
    Correo          VARCHAR2(100) NULL UNIQUE,
    CONSTRAINT CK_Cli_Correo CHECK (REGEXP_LIKE(Correo, '^[^@ ]+@[^@ ]+\.[^@ ]+$'))
);

CREATE TABLE SUCURSALES (
    ID_Sucursal     NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Nombre_Sucursal VARCHAR2(100) NOT NULL UNIQUE,
    Direccion       VARCHAR2(200) NOT NULL,
    Telefono        VARCHAR2(15)  NOT NULL
);

CREATE TABLE ROLES (
    ID_Rol      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Nombre_Rol  VARCHAR2(50)  NOT NULL UNIQUE,
    Descripcion VARCHAR2(150) NULL
);

CREATE TABLE METODOS_PAGO (
    ID_Metodo_Pago NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Nombre_Metodo  VARCHAR2(50) NOT NULL UNIQUE
);

-- ---------- 2.3 Tablas de personal y seguridad ----------
CREATE TABLE EMPLEADOS (
    ID_Empleado        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    DPI_Cedula         VARCHAR2(20)  NOT NULL UNIQUE,
    Nombre_Completo    VARCHAR2(100) NOT NULL,
    Cargo              VARCHAR2(50)  NOT NULL,
    Salario            NUMBER(10,2)  NOT NULL CHECK (Salario > 0),
    Fecha_Contratacion DATE DEFAULT SYSDATE NOT NULL,
    ID_Sucursal        NUMBER NOT NULL,
    CONSTRAINT FK_Emp_Sucursal FOREIGN KEY (ID_Sucursal) REFERENCES SUCURSALES(ID_Sucursal)
);

CREATE TABLE USUARIOS (
    ID_Usuario    NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Username      VARCHAR2(50)  NOT NULL UNIQUE,
    Password_Hash VARCHAR2(128) NOT NULL,
    Estado        VARCHAR2(10) DEFAULT 'ACTIVO' NOT NULL CHECK (Estado IN ('ACTIVO', 'INACTIVO')),
    ID_Empleado   NUMBER NOT NULL UNIQUE,
    ID_Rol        NUMBER NOT NULL,
    CONSTRAINT FK_Usu_Empleado FOREIGN KEY (ID_Empleado) REFERENCES EMPLEADOS(ID_Empleado) ON DELETE CASCADE,
    CONSTRAINT FK_Usu_Rol      FOREIGN KEY (ID_Rol)      REFERENCES ROLES(ID_Rol)
);

-- ---------- 2.4 Productos e inventario ----------
CREATE TABLE PRODUCTOS (
    ID_Producto     NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Codigo_Barras   VARCHAR2(50)  NOT NULL UNIQUE,
    Nombre_Producto VARCHAR2(100) NOT NULL,
    Precio_Compra   NUMBER(10,2)  NOT NULL CHECK (Precio_Compra > 0),
    Precio_Venta    NUMBER(10,2)  NOT NULL CHECK (Precio_Venta > 0),
    Stock_Actual    NUMBER(8)     NOT NULL CHECK (Stock_Actual >= 0),
    Stock_Minimo    NUMBER(8)     DEFAULT 5 NOT NULL CHECK (Stock_Minimo >= 0),
    ID_Categoria    NUMBER NOT NULL,
    ID_Proveedor    NUMBER NOT NULL,
    CONSTRAINT CK_Prod_Margen CHECK (Precio_Venta >= Precio_Compra),
    CONSTRAINT FK_Prod_Cat  FOREIGN KEY (ID_Categoria) REFERENCES CATEGORIAS(ID_Categoria),
    CONSTRAINT FK_Prod_Prov FOREIGN KEY (ID_Proveedor) REFERENCES PROVEEDORES(ID_Proveedor)
);

-- ---------- 2.5 Facturacion (ventas) ----------
CREATE TABLE FACTURAS_ENCABEZADO (
    ID_Factura       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Numero_Factura   VARCHAR2(20) NOT NULL UNIQUE,
    Fecha_Emision    DATE DEFAULT SYSDATE NOT NULL,
    Subtotal_Factura NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (Subtotal_Factura >= 0),
    Impuesto_IVA     NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (Impuesto_IVA >= 0),
    Total_Factura    NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (Total_Factura >= 0),
    Estado           VARCHAR2(10) DEFAULT 'PENDIENTE' NOT NULL
                     CHECK (Estado IN ('PENDIENTE', 'PAGADO', 'ANULADO')),
    ID_Cliente       NUMBER NOT NULL,
    ID_Empleado      NUMBER NOT NULL,
    CONSTRAINT CK_Fac_Total CHECK (Total_Factura = Subtotal_Factura + Impuesto_IVA),
    CONSTRAINT FK_Fac_Cli FOREIGN KEY (ID_Cliente)  REFERENCES CLIENTES(ID_Cliente),
    CONSTRAINT FK_Fac_Emp FOREIGN KEY (ID_Empleado) REFERENCES EMPLEADOS(ID_Empleado)
);

CREATE TABLE FACTURAS_DETALLE (
    ID_Detalle      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_Factura      NUMBER NOT NULL,
    ID_Producto     NUMBER NOT NULL,
    Cantidad        NUMBER(6)    NOT NULL CHECK (Cantidad > 0),
    Precio_Unitario NUMBER(10,2) NOT NULL CHECK (Precio_Unitario > 0),
    Subtotal        NUMBER(12,2) GENERATED ALWAYS AS (Cantidad * Precio_Unitario) VIRTUAL,
    CONSTRAINT CK_FDet_Subtotal CHECK (Subtotal > 0),
    CONSTRAINT FK_Det_Fac  FOREIGN KEY (ID_Factura)  REFERENCES FACTURAS_ENCABEZADO(ID_Factura),
    CONSTRAINT FK_Det_Prod FOREIGN KEY (ID_Producto) REFERENCES PRODUCTOS(ID_Producto)
);

CREATE TABLE PAGOS_FACTURA (
    ID_Pago            NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Monto_Pagado       NUMBER(12,2) NOT NULL CHECK (Monto_Pagado > 0),
    Fecha_Pago         DATE DEFAULT SYSDATE NOT NULL,
    Numero_Transaccion VARCHAR2(50) NULL,
    ID_Factura         NUMBER NOT NULL,
    ID_Metodo_Pago     NUMBER NOT NULL,
    CONSTRAINT FK_Pag_Factura FOREIGN KEY (ID_Factura)     REFERENCES FACTURAS_ENCABEZADO(ID_Factura),
    CONSTRAINT FK_Pag_Metodo  FOREIGN KEY (ID_Metodo_Pago) REFERENCES METODOS_PAGO(ID_Metodo_Pago)
);

-- ---------- 2.6 Compras a proveedores ----------
CREATE TABLE ORDENES_COMPRA (
    ID_Orden_Compra NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Numero_Orden    VARCHAR2(20) NOT NULL UNIQUE,
    Fecha_Orden     DATE DEFAULT SYSDATE NOT NULL,
    Total_Compra    NUMBER(12,2) DEFAULT 0 NOT NULL CHECK (Total_Compra >= 0),
    Estado_Orden    VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL
                    CHECK (Estado_Orden IN ('PENDIENTE', 'RECIBIDA', 'ANULADA')),
    ID_Proveedor    NUMBER NOT NULL,
    ID_Sucursal     NUMBER NOT NULL,
    CONSTRAINT FK_OC_Proveedor FOREIGN KEY (ID_Proveedor) REFERENCES PROVEEDORES(ID_Proveedor),
    CONSTRAINT FK_OC_Sucursal  FOREIGN KEY (ID_Sucursal)  REFERENCES SUCURSALES(ID_Sucursal)
);

CREATE TABLE ORDENES_COMPRA_DETALLE (
    ID_Orden_Detalle       NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_Orden_Compra        NUMBER NOT NULL,
    ID_Producto            NUMBER NOT NULL,
    Cantidad               NUMBER(6)    NOT NULL CHECK (Cantidad > 0),
    Precio_Compra_Unitario NUMBER(10,2) NOT NULL CHECK (Precio_Compra_Unitario > 0),
    Subtotal               NUMBER(12,2) GENERATED ALWAYS AS (Cantidad * Precio_Compra_Unitario) VIRTUAL,
    CONSTRAINT CK_OCDet_Subtotal CHECK (Subtotal > 0),
    CONSTRAINT UQ_OCDet_Orden_Prod UNIQUE (ID_Orden_Compra, ID_Producto),
    CONSTRAINT FK_OCDet_Orden FOREIGN KEY (ID_Orden_Compra) REFERENCES ORDENES_COMPRA(ID_Orden_Compra),
    CONSTRAINT FK_OCDet_Prod  FOREIGN KEY (ID_Producto)     REFERENCES PRODUCTOS(ID_Producto)
);

-- ---------- 2.7 Kardex: movimientos de inventario ----------
CREATE TABLE MOVIMIENTOS_INVENTARIO (
    ID_Movimiento    NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ID_Producto      NUMBER NOT NULL,
    Fecha_Movimiento DATE DEFAULT SYSDATE NOT NULL,
    Tipo_Movimiento  VARCHAR2(10) NOT NULL CHECK (Tipo_Movimiento IN ('ENTRADA', 'SALIDA')),
    Cantidad         NUMBER(8)    NOT NULL CHECK (Cantidad > 0),
    Saldo_Resultante NUMBER(8)    NOT NULL CHECK (Saldo_Resultante >= 0),
    Motivo           VARCHAR2(100) NOT NULL,
    ID_Factura       NUMBER NULL,
    ID_Orden_Compra  NUMBER NULL,
    CONSTRAINT CK_Mov_Origen CHECK (ID_Factura IS NULL OR ID_Orden_Compra IS NULL),
    CONSTRAINT FK_Mov_Prod FOREIGN KEY (ID_Producto)     REFERENCES PRODUCTOS(ID_Producto),
    CONSTRAINT FK_Mov_Fac  FOREIGN KEY (ID_Factura)      REFERENCES FACTURAS_ENCABEZADO(ID_Factura) ON DELETE SET NULL,
    CONSTRAINT FK_Mov_OC   FOREIGN KEY (ID_Orden_Compra) REFERENCES ORDENES_COMPRA(ID_Orden_Compra) ON DELETE SET NULL
);

-- ---------- 2.8 Indices de apoyo sobre llaves foraneas ----------
-- Oracle no crea indices automaticos para las FK; estos aceleran los JOIN de los reportes.
CREATE INDEX IDX_PROD_CAT    ON PRODUCTOS (ID_Categoria);
CREATE INDEX IDX_PROD_PROV   ON PRODUCTOS (ID_Proveedor);
CREATE INDEX IDX_FAC_CLI     ON FACTURAS_ENCABEZADO (ID_Cliente);
CREATE INDEX IDX_FAC_EMP     ON FACTURAS_ENCABEZADO (ID_Empleado);
CREATE INDEX IDX_FAC_FECHA   ON FACTURAS_ENCABEZADO (Fecha_Emision);
CREATE INDEX IDX_DET_FAC     ON FACTURAS_DETALLE (ID_Factura);
CREATE INDEX IDX_DET_PROD    ON FACTURAS_DETALLE (ID_Producto);
CREATE INDEX IDX_PAG_FAC     ON PAGOS_FACTURA (ID_Factura);
CREATE INDEX IDX_OC_PROV     ON ORDENES_COMPRA (ID_Proveedor);
CREATE INDEX IDX_MOV_PROD    ON MOVIMIENTOS_INVENTARIO (ID_Producto);
CREATE INDEX IDX_MOV_FAC     ON MOVIMIENTOS_INVENTARIO (ID_Factura);
CREATE INDEX IDX_MOV_OC      ON MOVIMIENTOS_INVENTARIO (ID_Orden_Compra);
CREATE INDEX IDX_EMP_SUC     ON EMPLEADOS (ID_Sucursal);
